# Вычисляет площадь треугольника по основанию и высоте
# Пример вызова:
# triangle_area(10, 5) = 25
def triangle_area(a, b):
	return a * b / 2

# Вычисляет периметр треугольника
# Пример вызова:
# triangle_perimetr(10, 5, 3) = 18
def triangle_perimetr(a, b, c):
	return a + b + c

# Вычисляет площядь квадрата
# Пример вызова:
# triangle_perimetr(10) = 100
def square_area(a):
	return a * a

# Вычисляет периметр квадрата
# Пример вызова:
# triangle_perimetr(10) = 40
def square_perimetr(a):
	return a * 4